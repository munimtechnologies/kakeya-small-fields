"""Checks for Proposition 31' (draft for kakeya-small-fields 1.7): normal one-sided designs.

Proposition 31'. Let G be a finite group, r >= 1, L a NORMAL subgroup of G and K a subset with
K L = K. Fix j in 1..r and let D be a set of r-tuples d with d_j in L such that K contains a left
translate A Y(d) of the cube Y_t = d_1^(t_1) ... d_r^(t_r). Then
    |D| <= |K|^r.
Proof: pass to Gbar = G/L. For i != j, Abar and Abar dbar_i lie in Kbar = K/L, so the (r-1)-tuple
(dbar_i) takes at most |Kbar|^r values; each dbar_i has |L| lifts and d_j has |L| choices, so
|D| <= |Kbar|^r |L|^(r-1) |L| = |K|^r. Equality: K = L = G, D = G^r.

So such designs satisfy |K| >= |D|^(1/r) > |D|^((1 - 2^-r)/r): they never lose against the abelian
exponent, whatever G' is. Normality is needed: in AGL(1, 5) with L = {x -> ax} (not normal) and
K = L u (x -> x + 1) L, r = 2, j = 2, every d in G x L is served, so |D| = 80 > 64 = |K|^2.

The script checks the bound for every normal L, every j and every union K of left L-cosets up to a
size cap (sampled when there are too many) in S_3, D_4, Q_8, A_4 and AGL(1, 5), r = 1, 2, 3.

    python prop31_cubes.py --out-dir OUT
"""
import argparse
import itertools
import json
import os
import random


# ---- groups as multiplication tables on 0..n-1, identity 0 --------------------------------

def closure(gens, mul, identity):
    elems, seen, frontier = [identity], {identity}, [identity]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = mul(x, g)
                if y not in seen:
                    seen.add(y)
                    elems.append(y)
                    new.append(y)
        frontier = new
    return elems


def table_from(elems, mul):
    index = {x: n for n, x in enumerate(elems)}
    return [[index[mul(a, b)] for b in elems] for a in elems]


def perm_mul(p, q):
    return tuple(p[q[i]] for i in range(len(p)))


def perm_group(gens):
    identity = tuple(range(len(gens[0])))
    elems = closure(gens, perm_mul, identity)
    return table_from(elems, perm_mul)


def quat_mul(u, v):
    a1, b1, c1, d1 = u
    a2, b2, c2, d2 = v
    return (a1 * a2 - b1 * b2 - c1 * c2 - d1 * d2,
            a1 * b2 + b1 * a2 + c1 * d2 - d1 * c2,
            a1 * c2 - b1 * d2 + c1 * a2 + d1 * b2,
            a1 * d2 + b1 * c2 - c1 * b2 + d1 * a2)


def groups():
    q8 = closure([(0, 1, 0, 0), (0, 0, 1, 0)], quat_mul, (1, 0, 0, 0))
    return {
        "S_3": perm_group([(1, 0, 2), (1, 2, 0)]),
        "D_4": perm_group([(1, 2, 3, 0), (0, 3, 2, 1)]),
        "Q_8": table_from(q8, quat_mul),
        "A_4": perm_group([(1, 2, 0, 3), (1, 0, 3, 2)]),
        "AGL(1,5)": perm_group([tuple(2 * x % 5 for x in range(5)),
                                tuple((x + 1) % 5 for x in range(5))]),
    }


def inverses(T):
    return [row.index(0) for row in T]


def generated(T, gens):
    return frozenset(closure(list(gens), lambda a, b: T[a][b], 0))


def normal_subgroups(T):
    """Every normal subgroup generated by at most two elements (all of them, for these groups)."""
    n, inv = len(T), inverses(T)
    found = set()
    for x in range(n):
        for y in range(x, n):
            L = generated(T, (x, y))
            if all(T[T[g][h]][inv[g]] in L for g in range(n) for h in L):
                found.add(L)
    return sorted(found, key=lambda L: (len(L), sorted(L)))


def left_cosets(T, L):
    cosets, seen = [], set()
    for x in range(len(T)):
        if x not in seen:
            c = frozenset(T[x][l] for l in L)
            cosets.append(c)
            seen |= c
    return cosets


# ---- served tuples -------------------------------------------------------------------------

def cube_in(T, K, A, d):
    pts = [A]
    for x in d:
        pts = pts + [T[p][x] for p in pts]
    return all(p in K for p in pts)


def served(T, K, r, j, L):
    """All r-tuples d with d_j in L (j is 0-based) having a left translate of their cube in K."""
    inv, out = inverses(T), set()
    for A in K:
        right = [T[inv[A]][k] for k in K]
        choices = [sorted(L) if i == j else right for i in range(r)]
        for d in itertools.product(*choices):
            if d not in out and cube_in(T, K, A, d):
                out.add(d)
    return out


def unions(cosets, size, cap, limit, rng):
    """Unions of left cosets with at most cap elements; a seeded sample if there are too many."""
    most = min(len(cosets), cap // size)
    combos = [c for k in range(1, most + 1) for c in itertools.combinations(range(len(cosets)), k)]
    if len(combos) > limit:
        combos = rng.sample(combos, limit)
    return [frozenset().union(*(cosets[i] for i in c)) for c in combos]


def check(T, r, cap, limit, seed=0):
    """Returns (sets checked, violations, equalities, max |D| / |K|^r)."""
    rng = random.Random(seed)
    checked, violations, equal, worst = 0, [], 0, 0.0
    for L in normal_subgroups(T):
        for K in unions(left_cosets(T, L), len(L), cap, limit, rng):
            for j in range(r):
                D = served(T, K, r, j, L)
                bound = len(K) ** r
                checked += 1
                worst = max(worst, len(D) / bound)
                if len(D) > bound:
                    violations.append({"L": sorted(L), "K": sorted(K), "j": j + 1, "D": len(D)})
                elif len(D) == bound:
                    equal += 1
    return checked, violations, equal, worst


def agl_contrast():
    """Non-normal L in AGL(1, 5): returns (|D|, |K|^2) for the design in the docstring."""
    T = groups()["AGL(1,5)"]
    L = generated(T, (1,))                      # index 1 is x -> 2x, generating {x -> ax}
    shift = 2                                   # index 2 is x -> x + 1
    K = L | frozenset(T[shift][l] for l in L)
    return len(served(T, K, 2, 1, L)), len(K) ** 2


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", default="out")
    args = ap.parse_args()
    os.makedirs(args.out_dir, exist_ok=True)
    report = {}
    for name, T in groups().items():
        for r, cap in ((1, 20), (2, 12), (3, 6)):
            checked, violations, equal, worst = check(T, r, cap, limit=400)
            report[f"{name} r={r}"] = {"checked": checked, "violations": violations,
                                       "equalities": equal, "max_ratio": worst}
            print(f"{name} r={r}: checked {checked}, violations {len(violations)}, "
                  f"equalities {equal}, max |D|/|K|^r {worst:.4f}")
    d, bound = agl_contrast()
    report["agl_contrast"] = {"D": d, "K^2": bound}
    print(f"AGL(1,5) non-normal contrast: |D| = {d} > |K|^2 = {bound}")
    with open(os.path.join(args.out_dir, "prop31.json"), "w") as f:
        json.dump(report, f, indent=1)


if __name__ == "__main__":
    main()
