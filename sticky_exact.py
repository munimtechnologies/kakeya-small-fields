# sticky_exact.py -- exact minimum size U*(n) of sticky Kakeya sets in F_3^n, by CP-SAT, plus the
# game-side bound G(5) of note a186 (Corollary 74.1).  Pre-registered in
# notes/prereg-sticky-exact.md before any run.
# MV2 of Munim, Inc. (mv2@munimtech.com). Made with AI agents working in MV2's name.
# Licence: Apache-2.0.  Needs ortools for the solver runs; everything else is stdlib.
#
# Model ("full"): for every prefix a of length < n and x in F_3, one-hot g_a(x) in F_3; one Boolean
# per point z of F_3^n.  For every direction d != 0, slice t and point z, the clause
#   [g_{d<j}(d_j) = z_j - t d_j for all j]  ->  z in K.
# Minimise |K|.  Translations act on every depth separately, so per depth j we fix
# g_{(1,...,1)}(1) = 0 (prefix of j ones).
# Model ("reduced"): Theorem 74 of a186.  Root map (0,0,0) (c0 = 0, hidden slice h = 0), and the
# subtree x = 2 is the relabelled copy of the subtree x = 1:  g_{2a}(y) = g_{1(-a)}(-y).
# Both models have optimum U*(n).  Every solution is re-checked in pure Python.

import argparse
import itertools
import json
import math
import time

import sticky_planes as sp


def prefixes(n):
    out = []
    for j in range(n):
        out.extend(itertools.product(range(3), repeat=j))
    return out


def neg(a):
    return tuple((-v) % 3 for v in a)


def normalize(maps, n):
    """Translate so that g_{(1,)*j}(1) = 0 for every depth j (the solver's symmetry fix)."""
    out = dict(maps)
    for j in range(n):
        shift = maps[(1,) * j][1]
        for a in itertools.product(range(3), repeat=j):
            out[a] = tuple((v - shift) % 3 for v in maps[a])
    return out


def is_reduced_form(maps, n):
    if maps[()] != (0, 0, 0):
        return False
    for a in prefixes(n - 1):
        for y in range(3):
            if maps[(2,) + a][y] != maps[(1,) + neg(a)][(-y) % 3]:
                return False
    return True


def build(n, reduced):
    from ortools.sat.python import cp_model
    m = cp_model.CpModel()
    G = {}
    for a in prefixes(n):
        name = "".join(map(str, a)) or "r"
        for x in range(3):
            lits = [m.NewBoolVar("g%s_%d_%d" % (name, x, v)) for v in range(3)]
            m.AddExactlyOne(lits)
            for v in range(3):
                G[(a, x, v)] = lits[v]
    pts = list(itertools.product(range(3), repeat=n))
    K = {z: m.NewBoolVar("k" + "".join(map(str, z))) for z in pts}
    for d in pts:
        if not any(d):
            continue
        for t in range(3):
            for z in pts:
                lits = [G[(d[:j], d[j], (z[j] - t * d[j]) % 3)].Not() for j in range(n)]
                m.AddBoolOr(lits + [K[z]])
    for j in range(n):
        m.Add(G[((1,) * j, 1, 0)] == 1)
    if reduced and n >= 2:
        for x in range(3):
            m.Add(G[((), x, 0)] == 1)
        for a in prefixes(n - 1):
            for y in range(3):
                for v in range(3):
                    m.Add(G[((2,) + a, y, v)] == G[((1,) + neg(a), (-y) % 3, v)])
    m.Minimize(sum(K.values()))
    return m, G, K


def solve(n, reduced, tlimit, workers):
    from ortools.sat.python import cp_model
    m, G, K = build(n, reduced)
    s = cp_model.CpSolver()
    s.parameters.max_time_in_seconds = float(tlimit)
    s.parameters.num_workers = int(workers)
    t0 = time.time()
    st = s.Solve(m)
    rec = {"n": n, "model": "reduced" if reduced else "full", "status": s.StatusName(st),
           "seconds": round(time.time() - t0, 1), "time_limit": tlimit}
    bnd = s.BestObjectiveBound()
    bound = int(math.ceil(bnd - 1e-6)) if math.isfinite(bnd) else None
    if st in (cp_model.OPTIMAL, cp_model.FEASIBLE):
        maps = {}
        for a in prefixes(n):
            maps[a] = tuple(next(v for v in range(3) if s.Value(G[(a, x, v)])) for x in range(3))
        Kset = sp.kakeya_set(maps, n)
        rec["objective"] = int(round(s.ObjectiveValue()))
        rec["bound"] = bound
        rec["verified_size"] = len(Kset)
        rec["is_kakeya"] = sp.is_kakeya(Kset, n)
        rec["maps"] = {("".join(map(str, a)) or "root"): list(g) for a, g in sorted(maps.items())}
        rec["points"] = sorted("".join(map(str, z)) for z in Kset)
    else:
        rec["objective"] = None
        rec["bound"] = bound
        rec["verified_size"] = None
    return rec


def g5(U4):
    """Corollary 74.1 one level further: min over A_4 of plane_bound(a, U4).  A_4 is generated by
    node outputs over the Pareto front of A_3.  Pruning: the parent's coordinate sum is at least
    every child's coordinate sum, and plane_bound >= the coordinate sum."""
    F3 = sp.fronts(3)[3]
    best = min(sp.plane_bound(tuple(2 * v for v in a), U4) for a in F3)   # doubling, Lemma 154
    kids = sorted((a for a in F3 if sum(a) < best), key=sum)
    for c0 in kids:
        if sum(c0) >= best:
            break
        for c1 in kids:
            if sum(c1) >= best:
                break
            for c2 in kids:
                if sum(c2) >= best:
                    break
                c = (c0, c1, c2)
                for p in (sp.triangle(c), sp.affine(c, 0), sp.affine(c, 1), sp.affine(c, 2)):
                    v = sp.plane_bound(p, U4)
                    if v < best:
                        best = v
    return {"U4_used": U4, "G5": best, "front3_size": len(F3)}


def verdict(recs):
    """Pre-registered rules (notes/prereg-sticky-exact.md)."""
    out = {}
    by = {(r["n"], r["model"]): r for r in recs}
    sane = True
    for n, want in ((2, 7), (3, 15)):
        for model in ("full", "reduced"):
            r = by.get((n, model))
            if r is None or r["status"] != "OPTIMAL" or r["objective"] != want \
                    or r["verified_size"] != want:
                sane = False
    out["sanity"] = "OK" if sane else "BUG"
    r4 = [r for r in recs if r["n"] == 4]
    sizes = [r["verified_size"] for r in r4 if r.get("verified_size") is not None]
    bounds = [r["bound"] for r in r4 if r.get("bound") is not None]
    best_size = min(sizes) if sizes else None
    best_bound = max(bounds) if bounds else None
    out["n4_best_verified_size"] = best_size
    out["n4_best_bound"] = best_bound
    if best_size is not None and best_size < 29:
        out["n4"] = "BUG"
    elif best_size is not None and best_bound is not None and best_bound > best_size:
        out["n4"] = "BUG"
    elif best_size is not None and best_size <= 30:
        out["n4"] = "S4-BREAK"
    elif best_bound is not None and best_bound >= 31:
        out["n4"] = "S4-CLASSICAL"
    else:
        out["n4"] = "UNDECIDED"
    r5 = [r for r in recs if r["n"] == 5]
    s5 = [r["verified_size"] for r in r5 if r.get("verified_size") is not None]
    b5 = [r["bound"] for r in r5 if r.get("bound") is not None]
    out["n5_best_verified_size"] = min(s5) if s5 else None
    out["n5_best_bound"] = max(b5) if b5 else None
    flags = []
    if s5 and min(s5) <= 62:
        flags.append("S5-BREAK")
    if b5 and max(b5) >= 57:
        flags.append("S5-SEPARATION")
    out["n5"] = flags or ["UNDECIDED"]
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="sticky_exact.json")
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--t4r", type=int, default=4500)
    ap.add_argument("--t4f", type=int, default=3000)
    ap.add_argument("--t5", type=int, default=3600)
    ap.add_argument("--skip5", action="store_true")
    args = ap.parse_args()
    res = {"made_with": "AI agents working in MV2's name; no human has checked this",
           "runs": [], "game": []}

    def dump():
        res["verdict"] = verdict(res["runs"])
        with open(args.out, "w") as fh:
            json.dump(res, fh, indent=1)

    plan = [(2, False, 60), (2, True, 60), (3, False, 300), (3, True, 300),
            (4, True, args.t4r), (4, False, args.t4f)]
    if not args.skip5:
        plan.append((5, True, args.t5))
    for n, reduced, tl in plan:
        rec = solve(n, reduced, tl, args.workers)
        res["runs"].append(rec)
        print(json.dumps({k: rec.get(k) for k in ("n", "model", "status", "objective", "bound",
                                                   "verified_size", "seconds")}), flush=True)
        dump()
        if n == 4 and not reduced:
            res["game"].append(g5(29))
            v = verdict(res["runs"])
            b = v.get("n4_best_bound")
            if v.get("n4") != "BUG" and b is not None and b > 29:
                res["game"].append(g5(min(b, 31)))
            print(json.dumps(res["game"]), flush=True)
            dump()
    dump()


if __name__ == "__main__":
    main()
