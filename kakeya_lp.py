KT_WORD = {"steps": [
    {"block": [0], "glue": [[0, "x"]]},
    {"block": [0, 1], "glue": [[0, "s"], [1, "s"]]},
    {"block": [2, 3], "glue": [[2, "y"], [3, "y"]]},
    {"block": [4, 5], "glue": [[4, "s"], [5, "y"]]},
]}


def chain_word(root_glue, glues):
    """Root copy over root_glue (a reading of vertex 0), then copy the newest page
    (two vertices) over each glue in turn. Glue entries use page positions 0/1."""
    steps = [{"block": [0], "glue": [[0, root_glue]]}]
    page = [0, 1]
    nxt = 2
    for g in glues:
        steps.append({"block": list(page), "glue": [[page[p], k] for p, k in g]})
        page = [nxt, nxt + 1]
        nxt += 2
    return {"steps": steps}


def page_glues():
    reads = [(p, k) for p in (0, 1) for k in READINGS]
    out = [[g] for g in reads] + [list(c) for c in itertools.combinations(reads, 2)]
    return out


def extras_s(cfg):
    return [[[v, "s", 1]] for v in range(len(cfg.vx))]


def extras_cross(cfg, rng, count):
    n = len(cfg.vx)
    cands = []
    for v in range(n):
        for w in range(v + 1, n):
            for k1 in ("x", "y", "s", "d"):
                for k2 in ("x", "y", "s", "d"):
                    cands.append([[v, k1, 1], [w, k2, 2]])
                    cands.append([[v, k1, 1], [w, k2, 1]])
    rng.shuffle(cands)
    return cands[:count]


