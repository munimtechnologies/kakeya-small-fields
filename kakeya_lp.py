READINGS = ("x", "y", "s", "d")


class Config:
    """Vertices (Kakeya pairs) built from the root by copy steps (the 'word')."""

    def __init__(self, word=None):
        self.r = 2
        self.vx = [(1, 0)]
        self.vy = [(0, 1)]
        self.steps = []
        if word is not None:
            for st in word["steps"]:
                self.copy(st["block"], [tuple(g) for g in st["glue"]])

    def reading(self, v, kind, r=None):
        r = self.r if r is None else r
        x, y = pad(self.vx[v], r), pad(self.vy[v], r)
        if kind == "x":
            return x
        if kind == "y":
            return y
        if kind == "s":
            return vadd(x, y)
        if kind == "d":
            return vsub(y, x)
        raise ValueError(kind)

    def vertices(self, ids=None, r=None):
        r = self.r if r is None else r
        ids = range(len(self.vx)) if ids is None else ids
        return [(pad(self.vx[v], r), pad(self.vy[v], r)) for v in ids]

    def copy(self, block, glue):
        block = list(block)
        if len(set(block)) != len(block) or not block:
            raise ValueError("bad block")
        for v, k in glue:
            if v not in block or k not in READINGS:
                raise ValueError("glue must be readings of block vertices")
        r0 = self.r
        gforms = [self.reading(v, k) for v, k in glue]
        bverts = self.vertices(block)
        gstar = closure(gforms, bverts)
        cur = gstar
        kappa = []
        for (x, y) in bverts:
            for u in (x, y):
                if not in_span(u, cur):
                    kappa.append(u)
                    cur = rref(list(cur) + [u])
        if not kappa:
            raise ValueError("trivial copy (glue determines the block)")
        m = len(kappa)
        newr = r0 + m
        basis = list(gstar) + kappa

        def phi(u, _r0=r0, _m=m, _basis=basis, _ng=len(gstar), _kappa=kappa, _newr=newr):
            u = pad(u, _r0)
            lam = decompose(u, _basis)
            if lam is None:
                raise ValueError("form not in the span of the block")
            g = list(u)
            for j in range(_m):
                c = lam[_ng + j]
                if c:
                    g = [(a - c * b) % 3 for a, b in zip(g, _kappa[j])]
            out = list(pad(tuple(g), _newr))
            for j in range(_m):
                out[_r0 + j] = lam[_ng + j] % 3
            return tuple(out)

        old_n = len(self.vx)
        newv = [(phi(x), phi(y)) for (x, y) in bverts]
        self.r = newr
        new_ids = []
        for x, y in newv:
            self.vx.append(x)
            self.vy.append(y)
            new_ids.append(len(self.vx) - 1)
        self.steps.append({"block": block, "glue": [list(g) for g in glue], "gforms": gforms,
                           "gstar": gstar, "kappa": kappa, "r0": r0, "old_n": old_n,
                           "new": new_ids, "phi": phi})
        return new_ids

    def block_span(self, s):
        st = self.steps[s]
        return rref([u for xy in self.vertices(st["block"], r=st["r0"]) for u in xy])


def build_atoms(cfg, extras=()):
    """Atom list: every vertex x and y form, then glue forms (not 'd'), then extras.
    Duplicates and zero forms are skipped. extras: list of [[v, kind, coef], ...]."""
    R = cfg.r
    forms, names, seen = [], [], set()

    def add(f, name):
        f = pad(f, R)
        if not any(f) or f in seen:
            return
        seen.add(f)
        forms.append(f)
        names.append(name)

    for v in range(len(cfg.vx)):
        add(cfg.reading(v, "x"), "x%d" % v)
        add(cfg.reading(v, "y"), "y%d" % v)
    for st in cfg.steps:
        for v, k in st["glue"]:
            if k != "d":
                add(cfg.reading(v, k), "%s%d" % (k, v))
    for comb in extras:
        f = (0,) * R
        for v, k, c in comb:
            f = vadd(f, vscale(c % 3, cfg.reading(v, k)))
        add(f, "+".join("%d%s%d" % (c % 3, k, v) for v, k, c in comb))
    return forms, names


