def solve(model):
    import numpy as np
    from scipy.optimize import linprog
    from scipy.sparse import csr_matrix

    nv = model.nvars()
    ub_r, ub_c, ub_v, b_ub = [], [], [], []
    eq_r, eq_c, eq_v, b_eq = [], [], [], []
    for sense, coefs, const, _ in model.rows:
        if sense == "ge":
            i = len(b_ub)
            for var, a in coefs.items():
                ub_r.append(i)
                ub_c.append(var)
                ub_v.append(-a)
            b_ub.append(const)
        else:
            i = len(b_eq)
            for var, a in coefs.items():
                eq_r.append(i)
                eq_c.append(var)
                eq_v.append(a)
            b_eq.append(-const)
    A_ub = csr_matrix((ub_v, (ub_r, ub_c)), shape=(len(b_ub), nv))
    A_eq = csr_matrix((eq_v, (eq_r, eq_c)), shape=(len(b_eq), nv))
    c = np.zeros(nv)
    c[model.t] = 1.0
    bounds = [(None, None)] * nv
    bounds[0] = (0, 0)
    res = linprog(c, A_ub=A_ub, b_ub=np.array(b_ub, dtype=float), A_eq=A_eq,
                  b_eq=np.array(b_eq, dtype=float), bounds=bounds, method="highs")
    if res.status != 0:
        return None, None, None, res.message
    ge_mu = [-float(x) for x in res.ineqlin.marginals]
    eq_mu = [float(x) for x in res.eqlin.marginals]
    return float(res.fun), ge_mu, eq_mu, "ok"


def run_one(word, extras, uniform, max_atoms, out_dir, tag, want_cert, log):
    t0 = time.time()
    try:
        model = Model(word, extras=extras, uniform=uniform, max_atoms=max_atoms)
    except TooBig as e:
        return {"tag": tag, "skipped": str(e)}
    except ValueError as e:
        return {"tag": tag, "invalid": str(e)}
    t1 = time.time()
    val, ge_mu, eq_mu, msg = solve(model)
    t2 = time.time()
    rec = {"tag": tag, "word": word, "extras": model.extras, "uniform": uniform,
           "atoms": model.m, "vars": model.nvars(), "rows": len(model.rows),
           "extra_keys": model.extra_keys, "value": val, "msg": str(msg),
           "build_s": round(t1 - t0, 1), "solve_s": round(t2 - t1, 1)}
    if val is not None and want_cert(val):
        bound, mults = None, "no sign convention worked"
        for sg, se in ((1, 1), (1, -1), (-1, 1), (-1, -1)):
            bound, mults = certificate_from_duals(model, [sg * x for x in ge_mu],
                                                  [se * x for x in eq_mu])
            if bound is not None:
                break
        if bound is None:
            rec["certificate"] = "failed: %s" % mults
        else:
            cert = export_certificate(model, bound, mults)
            try:
                import kakeya_cert_check
                checked = kakeya_cert_check.check(cert)
                rec["checked_bound"] = str(checked)
                rec["checked_float"] = float(checked)
            except Exception as e:  # noqa: BLE001 -- record any checker rejection
                rec["checker_error"] = repr(e)
            rec["exact_bound"] = str(bound)
            rec["exact_float"] = float(bound)
            name = "cert_%s.json" % tag
            with open(os.path.join(out_dir, name), "w") as fh:
                json.dump(cert, fh)
            rec["certificate"] = name
    log(rec)
    return rec


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", default="out")
    ap.add_argument("--minutes", type=float, default=150.0)
    ap.add_argument("--seed", type=int, default=20261118)
    ap.add_argument("--max-atoms", type=int, default=14)
    a = ap.parse_args(argv)
    os.makedirs(a.out_dir, exist_ok=True)
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    deadline = time.time() + 60 * a.minutes
    rng = random.Random(a.seed)
    results = []
    best = {"value": None}
    logf = open(os.path.join(a.out_dir, "results.jsonl"), "w")

    def log(rec):
        results.append(rec)
        logf.write(json.dumps(rec) + "\n")
        logf.flush()
        v = rec.get("value")
        if v is not None and (best["value"] is None or v > best["value"]):
            best.update(value=v, tag=rec["tag"])
        print(rec.get("tag"), rec.get("atoms"), rec.get("rows"), rec.get("value"),
              rec.get("exact_bound", ""), rec.get("checked_bound", ""), flush=True)

    hit = lambda v: v > float(KT_BOUND) + 1e-7  # noqa: E731
    always = lambda v: True  # noqa: E731

    # Phase 1: self-test on the Katz-Tao word (must give >= 6/11, certificate checked).
    base = run_one(KT_WORD, [], False, a.max_atoms, a.out_dir, "kt-base", always, log)
    cfg = Config(KT_WORD)
    run_one(KT_WORD, extras_s(cfg), False, a.max_atoms, a.out_dir, "kt-s", hit, log)
    for c in range(3):
        ex = extras_cross(cfg, rng, a.max_atoms - 12)
        r1 = run_one(KT_WORD, ex, True, a.max_atoms, a.out_dir, "kt-cross%d-u" % c, hit, log)
        if r1.get("value") is not None:
            run_one(KT_WORD, ex, False, a.max_atoms, a.out_dir, "kt-cross%d-n" % c, hit, log)
    selftest = {"kt_base_value": base.get("value"), "kt_base_exact": base.get("exact_bound"),
                "kt_base_checked": base.get("checked_bound")}

    # Phase 2: one-change neighbourhood of KT (root glue or one page glue), base atoms.
    kt_root = "x"
    kt_glues = [[(0, "s"), (1, "s")], [(0, "y"), (1, "y")], [(0, "s"), (1, "y")]]
    words = []
    for rg in ("y", "s"):
        words.append(("n-root-%s" % rg, chain_word(rg, kt_glues)))
    for pos in range(3):
        for gi, g in enumerate(page_glues()):
            gl = [list(x) for x in kt_glues]
            if [tuple(x) for x in g] == [tuple(x) for x in gl[pos]]:
                continue
            gl[pos] = g
            words.append(("n-%d-%d" % (pos, gi), chain_word(kt_root, gl)))
    for tag, w in words:
        if time.time() > deadline:
            break
        rec = run_one(w, [], False, a.max_atoms, a.out_dir, tag, hit, log)
        if rec.get("value") is not None and time.time() < deadline:
            c2 = Config(w)
            ex = extras_cross(c2, rng, max(0, a.max_atoms - rec["atoms"]))
            if ex:
                run_one(w, ex, True, a.max_atoms, a.out_dir, tag + "-u", hit, log)

    # Phase 3: random chains of length 3 and 4 (base atoms, then cross atoms + unif).
    pg = page_glues()
    n = 0
    while time.time() < deadline:
        L = rng.choice((3, 3, 4))
        w = chain_word(rng.choice(("x", "y", "s")), [rng.choice(pg) for _ in range(L)])
        tag = "r%d" % n
        n += 1
        rec = run_one(w, [], False, a.max_atoms, a.out_dir, tag, hit, log)
        if rec.get("value") is not None and time.time() < deadline:
            c2 = Config(w)
            ex = extras_cross(c2, rng, max(0, a.max_atoms - rec["atoms"]))
            if ex:
                run_one(w, ex, True, a.max_atoms, a.out_dir, tag + "-u", hit, log)

    vals = [r for r in results if r.get("value") is not None]
    summary = {
        "selftest": selftest,
        "lps_solved": len(vals),
        "skipped": sum(1 for r in results if "skipped" in r),
        "invalid": sum(1 for r in results if "invalid" in r),
        "best_value": best.get("value"),
        "best_tag": best.get("tag"),
        "kt_bound": float(KT_BOUND),
        "hits_checked": [r for r in results if r.get("checked_float", 0) > float(KT_BOUND)],
        "uniform_gain": [r["tag"] for r in results if r["tag"].endswith("-u")
                         and r.get("value") is not None
                         and r["value"] > float(KT_BOUND) + 1e-7],
    }
    with open(os.path.join(a.out_dir, "summary.json"), "w") as fh:
        json.dump(summary, fh, indent=1)
    logf.close()
    print(json.dumps(summary, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
