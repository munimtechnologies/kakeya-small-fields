"""kakeya_lp.py -- the Kakeya-restricted entropy LP over F_3.

MV2 of Munim, Inc. (mv2@munimtech.com). Made with AI agents working in MV2's name.
Licence: Apache-2.0. Pre-registration: notes/prereg-kakeya-lp.md.

Question. Over F_3 a Kakeya pair is (X, Y) = (a(D), a(D) + D) with D uniform on the whole
group G = F_3^k. The three readings x = X, y = Y, s = X + Y (= -(a + 2D)) all lie in K or -K.
Theorem 68 (note a180) uses the Katz-Tao inequality to prove
    (H(x) + H(y) + H(s)) / 3 >= (6/11) log|G|.
Can Shannon inequalities, copy-lemma gluing, F_3-linear closures (3-torsion) and the
Kakeya restriction "every G-valued variable has entropy <= H(D) = log|G|" prove a
constant above 6/11? Any such certificate is a new lower bound for Kakeya sets in F_3^n:
|K| >= |G|^c, i.e. base 3^c > 3^(6/11) = 1.82074.

Model. A configuration is a list of "vertices", each a copy of the Kakeya pair, with its
readings written as F_3-linear forms in abstract coordinates. The root vertex is (e0, e1).
A copy step copies a block of vertices conditionally on some of their readings (the glue),
independently of everything built so far (copy lemma). Fresh coordinates represent the
copied block modulo the glue. A set of forms S determines its closure cl(S): the F_3-span,
enlarged by "x_v, y_v whenever d_v = y_v - x_v is in the span" (x is a function of d).
H(S) = H(cl S), so LP variables are indexed by closures.

Rows (every row is valid for every Kakeya pair in every F_3^k):
  sub   I(i; j | K) >= 0 over the atoms (elemental Shannon inequalities)
  mono  H(all) - H(all minus i) >= 0
  mi    I(A; B | C) >= 0 for atom sets (used by hand certificates)
  copy  I(Old; New | glue) = 0 for each copy step
  law   H(cl S) = H(cl phi(S)) for atom sets S inside a copied block (equal joint law)
  norm  H(x_v, y_v) = 1 (units of log|G|; the pair is determined by the uniform D)
  read  H(r_v) = t for r in {x, y, s}  (see "rotation" below)
  unif  H(atom) <= 1 (Kakeya restriction: every G-valued variable has entropy <= log|G|)
Rotation. A certificate proves L <= bx H(x) + by H(y) + bs H(s) with bx + by + bs = gamma > 0
(signs free). The rotated pair (Y, -(X+Y)) = (a'(D), a'(D) + D) with a' = a + D is again a
Kakeya pair, and rotation cycles (H(x), H(y), H(s)). Summing the three rotations gives
(H(x) + H(y) + H(s)) / 3 >= L / gamma. So the LP may set all readings equal to one t.

Only the standard library is needed to build models, realise them on small examples, and
check certificates. Solving needs scipy (HiGHS); it is imported only inside solve().
"""

