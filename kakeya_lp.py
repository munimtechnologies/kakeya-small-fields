def pad(u, r):
    u = tuple(u)
    if len(u) > r:
        if any(u[r:]):
            raise ValueError("form does not fit in %d coordinates" % r)
        return u[:r]
    return u + (0,) * (r - len(u))


def vadd(u, v):
    return tuple((a + b) % 3 for a, b in zip(u, v))


def vsub(u, v):
    return tuple((a - b) % 3 for a, b in zip(u, v))


def vscale(c, u):
    return tuple((c * a) % 3 for a in u)


def rref(vecs):
    """Canonical reduced row echelon basis (tuple of tuples) of the span of vecs."""
    rows = [[a % 3 for a in v] for v in vecs]
    rows = [row for row in rows if any(row)]
    if not rows:
        return ()
    ncol = len(rows[0])
    r = 0
    for col in range(ncol):
        piv = None
        for i in range(r, len(rows)):
            if rows[i][col]:
                piv = i
                break
        if piv is None:
            continue
        rows[r], rows[piv] = rows[piv], rows[r]
        inv = 1 if rows[r][col] == 1 else 2
        rows[r] = [(inv * a) % 3 for a in rows[r]]
        for i in range(len(rows)):
            if i != r and rows[i][col]:
                c = rows[i][col]
                rows[i] = [(a - c * b) % 3 for a, b in zip(rows[i], rows[r])]
        r += 1
        if r == len(rows):
            break
    return tuple(tuple(row) for row in rows[:r])


def reduce_vec(v, basis):
    v = list(v)
    for row in basis:
        p = 0
        while not row[p]:
            p += 1
        c = v[p]
        if c:
            v = [(a - c * b) % 3 for a, b in zip(v, row)]
    return v


def in_span(v, basis):
    return not any(reduce_vec(v, basis))


def closure(vecs, vertices, start=()):
    """Closed set generated by vecs (plus the closed set `start`): span, then add x_v
    (hence y_v) whenever d_v = y_v - x_v lies in the span; repeat."""
    basis = rref(list(start) + list(vecs))
    changed = True
    while changed:
        changed = False
        for (x, y) in vertices:
            d = vsub(y, x)
            if in_span(d, basis) and not in_span(x, basis):
                basis = rref(list(basis) + [x])
                changed = True
    return basis


def decompose(v, basis):
    """Coefficients lam (mod 3) with sum lam_i basis_i = v, or None. basis independent."""
    n = len(basis)
    ech = []
    for i, b in enumerate(basis):
        vec = list(b)
        tag = [1 if j == i else 0 for j in range(n)]
        for (ev, et, p) in ech:
            c = vec[p]
            if c:
                vec = [(a - c * e) % 3 for a, e in zip(vec, ev)]
                tag = [(a - c * e) % 3 for a, e in zip(tag, et)]
        if not any(vec):
            raise ValueError("dependent basis")
        p = 0
        while not vec[p]:
            p += 1
        inv = 1 if vec[p] == 1 else 2
        vec = [(inv * a) % 3 for a in vec]
        tag = [(inv * a) % 3 for a in tag]
        ech.append((vec, tag, p))
    w = list(v)
    lam = [0] * n
    for (ev, et, p) in ech:
        c = w[p]
        if c:
            w = [(a - c * e) % 3 for a, e in zip(w, ev)]
            lam = [(a + c * e) % 3 for a, e in zip(lam, et)]
    if any(w):
        return None
    return lam


