def combine(model, mults):
    """mults: {row index: Fraction}. Returns (ok, bound, info). ok means: every 'ge'
    multiplier >= 0, every closure variable cancels, the t coefficient gamma > 0. Then
    t >= -const / gamma for every Kakeya pair."""
    tot = {}
    const = Fraction(0)
    for ri, mu in mults.items():
        sense, coefs, c, _ = model.rows[ri]
        if sense == "ge" and mu < 0:
            return False, None, "negative multiplier on row %d" % ri
        for var, a in coefs.items():
            tot[var] = tot.get(var, Fraction(0)) + mu * a
        const += mu * c
    gamma = tot.pop(model.t, Fraction(0))
    bad = [v for v, a in tot.items() if a != 0]
    if bad:
        return False, None, "%d variables do not cancel" % len(bad)
    if gamma <= 0:
        return False, None, "t coefficient %s is not positive" % gamma
    return True, -const / gamma, "ok"


def exact_solve(model, support, guess):
    """Exact rational multipliers on the support rows with sum mu * row = t + const.
    Free unknowns are set to their rationalised float values."""
    eqs = {}
    for idx, ri in enumerate(support):
        for var, a in model.rows[ri][1].items():
            eqs.setdefault(var, {})[idx] = Fraction(a)
    rhs = {var: Fraction(1 if var == model.t else 0) for var in eqs}
    if model.t not in eqs:
        return None
    piv = {}  # unknown -> (row dict over free unknowns, rhs)
    for var, row in eqs.items():
        row = dict(row)
        b = rhs[var]
        for u in [u for u in row if u in piv]:
            c = row.pop(u)
            prow, pb = piv[u]
            b -= c * pb
            for w, a in prow.items():
                row[w] = row.get(w, Fraction(0)) - c * a
                if row[w] == 0:
                    del row[w]
        if not row:
            if b != 0:
                return None
            continue
        u0 = max(row, key=lambda u: abs(row[u]))
        c0 = row.pop(u0)
        row = {w: a / c0 for w, a in row.items()}
        b = b / c0
        for u, (prow, pb) in list(piv.items()):
            if u0 in prow:
                c = prow.pop(u0)
                for w, a in row.items():
                    prow[w] = prow.get(w, Fraction(0)) - c * a
                    if prow[w] == 0:
                        del prow[w]
                piv[u] = (prow, pb - c * b)
        piv[u0] = (row, b)
    val = {}
    for idx in range(len(support)):
        if idx not in piv:
            val[idx] = guess[idx]
    for u, (prow, pb) in piv.items():
        val[u] = pb - sum(a * val[w] for w, a in prow.items())
    return {support[idx]: val[idx] for idx in range(len(support))}


def certificate_from_duals(model, ge_mu, eq_mu, tol=1e-10):
    """ge_mu, eq_mu: float multipliers per row in model order of 'ge' and 'eq' rows
    (mu >= 0 for ge). Returns (bound, mults) or (None, reason)."""
    support, guess_f = [], []
    gi = ei = 0
    for ri, row in enumerate(model.rows):
        if row[0] == "ge":
            mu = ge_mu[gi]
            gi += 1
        else:
            mu = eq_mu[ei]
            ei += 1
        if abs(mu) > tol:
            support.append(ri)
            guess_f.append(mu)
    for den in (10 ** 3, 10 ** 4, 10 ** 5, 10 ** 6):
        mults = {ri: Fraction(mu).limit_denominator(den) for ri, mu in zip(support, guess_f)}
        mults = {ri: (Fraction(0) if (model.rows[ri][0] == "ge" and q < 0) else q)
                 for ri, q in mults.items()}
        ok, bound, _ = combine(model, mults)
        if ok:
            return bound, mults
    guess = [Fraction(mu).limit_denominator(10 ** 6) for mu in guess_f]
    mults = exact_solve(model, support, guess)
    if mults is None:
        return None, "exact solve failed"
    ok, bound, info = combine(model, mults)
    if not ok:
        return None, info
    return bound, mults


def export_certificate(model, bound, mults):
    return {
        "format": "kakeya-lp-certificate-1",
        "word": model.word,
        "extras": model.extras,
        "uniform": model.uniform,
        "atoms": [[n, list(f)] for n, f in zip(model.names, model.forms)],
        "claimed_bound": str(bound),
        "rows": [{"d": model.desc_json(model.rows[ri][3]), "m": str(mu)}
                 for ri, mu in sorted(mults.items()) if mu != 0],
    }


