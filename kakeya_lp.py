class TooBig(Exception):
    pass


def bits(mask):
    out, i = [], 0
    while mask:
        if mask & 1:
            out.append(i)
        mask >>= 1
        i += 1
    return out


class Model:
    """Rows: (sense, coefs {var: int}, const, desc). sense 'ge': sum coef*h + const >= 0;
    'eq': = 0. Variable 0 is the empty closure (entropy 0, never used in rows); variable
    self.t is the common reading entropy t. Entropies are in units of log|G|."""

    def __init__(self, word, extras=(), uniform=True, max_atoms=14, elemental=True):
        self.word = word
        self.extras = [list(map(list, c)) for c in extras]
        self.uniform = uniform
        cfg = Config(word)
        self.cfg = cfg
        R = cfg.r
        self.R = R
        verts = cfg.vertices()
        self.verts = verts
        forms, names = build_atoms(cfg, extras)
        self.forms, self.names = forms, names
        m = len(forms)
        self.m = m
        if m > max_atoms:
            raise TooBig("%d atoms > %d" % (m, max_atoms))
        self.atom_index = {f: i for i, f in enumerate(forms)}
        cl = [()] * (1 << m)
        for mask in range(1, 1 << m):
            low = mask & -mask
            i = low.bit_length() - 1
            cl[mask] = closure([forms[i]], verts, start=cl[mask ^ low])
        self.cl = cl
        self.keys = []
        self.key_index = {}
        self.colof = [self.var_of(cl[mask]) for mask in range(1 << m)]
        self.n_closure_vars = len(self.keys)
        self.rows = []
        self._seen = set()
        self.extra_keys = 0
        if elemental:
            self._elemental()
        self._copy_rows()
        self._law_rows()
        self._norm_rows()
        self.t = None
        self._read_rows()
        if uniform:
            self._unif_rows()

    # --- variables ---
    def var_of(self, key):
        if key not in self.key_index:
            self.key_index[key] = len(self.keys)
            self.keys.append(key)
        return self.key_index[key]

    def key_of_forms(self, fs):
        return closure([pad(f, self.R) for f in fs], self.verts)

    def nvars(self):
        return len(self.keys) + 1  # + t

    # --- rows ---
    def add_row(self, sense, terms, const, desc):
        coefs = {}
        for var, c in terms:
            if var == 0 or c == 0:
                continue
            coefs[var] = coefs.get(var, 0) + c
        coefs = {k: v for k, v in coefs.items() if v}
        if not coefs and const == 0:
            return
        sig = (sense, tuple(sorted(coefs.items())), const)
        if sig in self._seen:
            return
        self._seen.add(sig)
        self.rows.append((sense, coefs, const, desc))

    def _elemental(self):
        m, colof = self.m, self.colof
        full = (1 << m) - 1
        for i in range(m):
            self.add_row("ge", [(colof[full], 1), (colof[full ^ (1 << i)], -1)], 0,
                         ("mono", i, full ^ (1 << i)))
        for i in range(m):
            for j in range(i + 1, m):
                rest = full ^ (1 << i) ^ (1 << j)
                bi, bj = 1 << i, 1 << j
                K = rest
                while True:
                    self.add_row("ge", [(colof[K | bi], 1), (colof[K | bj], 1),
                                        (colof[K | bi | bj], -1), (colof[K], -1)], 0,
                                 ("sub", i, j, K))
                    if K == 0:
                        break
                    K = (K - 1) & rest

    def _copy_rows(self):
        cfg = self.cfg
        for s, st in enumerate(cfg.steps):
            old = [u for xy in self.verts[:st["old_n"]] for u in xy]
            new = [u for v in st["new"] for u in self.verts[v]]
            kO = self.key_of_forms(old)
            kU = self.key_of_forms(new)
            kG = self.key_of_forms(st["gforms"])
            kOU = self.key_of_forms(old + new)
            n0 = len(self.keys)
            terms = [(self.var_of(kOU), 1), (self.var_of(kG), 1), (self.var_of(kO), -1),
                     (self.var_of(kU), -1)]
            self.extra_keys += len(self.keys) - n0
            self.add_row("eq", terms, 0, ("copy", s))

    def _law_rows(self):
        cfg = self.cfg
        for s, st in enumerate(cfg.steps):
            span = cfg.block_span(s)
            pairs = []
            for i, f in enumerate(self.forms):
                if any(f[st["r0"]:]):
                    continue
                if not in_span(f[:st["r0"]], span):
                    continue
                img = pad(st["phi"](f[:st["r0"]]), self.R)
                j = self.atom_index.get(img)
                if j is not None:  # glued atoms map to themselves and stay in S
                    pairs.append((i, j))
            for size in range(1, len(pairs) + 1):
                for sub in itertools.combinations(pairs, size):
                    ms = sum(1 << i for i, _ in sub)
                    mt = sum(1 << j for _, j in sub)
                    self.add_row("eq", [(self.colof[ms], 1), (self.colof[mt], -1)], 0,
                                 ("law", s, [i for i, _ in sub]))

    def _norm_rows(self):
        for v in range(len(self.verts)):
            x, y = self.verts[v]
            key = self.key_of_forms([x, y])
            n0 = len(self.keys)
            var = self.var_of(key)
            self.extra_keys += len(self.keys) - n0
            self.add_row("eq", [(var, 1)], -1, ("norm", v))

    def _read_rows(self):
        self.t = len(self.keys)  # t is the last variable; keys added later would collide
        for v in range(len(self.verts)):
            for r in ("x", "y", "s"):
                f = self.cfg.reading(v, r)
                i = self.atom_index.get(pad(f, self.R))
                if i is None:
                    continue
                self.add_row("eq", [(self.colof[1 << i], 1), (self.t, -1)], 0, ("read", v, r))

    def _unif_rows(self):
        for i in range(self.m):
            self.add_row("ge", [(self.colof[1 << i], -1)], 1, ("unif", i))

    # --- export ---
    def desc_json(self, desc):
        k = desc[0]
        if k == "mono":
            return {"k": "mono", "i": desc[1], "K": bits(desc[2])}
        if k == "sub":
            return {"k": "sub", "i": desc[1], "j": desc[2], "K": bits(desc[3])}
        if k == "copy":
            return {"k": "copy", "step": desc[1]}
        if k == "law":
            return {"k": "law", "step": desc[1], "S": list(desc[2])}
        if k == "norm":
            return {"k": "norm", "v": desc[1]}
        if k == "read":
            return {"k": "read", "v": desc[1], "r": desc[2]}
        if k == "unif":
            return {"k": "unif", "i": desc[1]}
        raise ValueError(k)


