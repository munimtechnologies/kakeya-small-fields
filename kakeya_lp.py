def realize(cfg, pmap):
    """Exact joint law (dict coordinate tuple -> Fraction) of the configuration built
    from the Kakeya map P: F_3 -> F_3 given as pmap[0..2]: D = X uniform, x = P(X),
    y = P(X) + X."""
    law = {}
    for X in range(3):
        a = pmap[X] % 3
        b = (pmap[X] + X) % 3
        law[(a, b)] = law.get((a, b), Fraction(0)) + Fraction(1, 3)

    def ev(form, w):
        return sum(c * x for c, x in zip(form, w)) % 3

    for st in cfg.steps:
        gstar, kappa = st["gstar"], st["kappa"]
        gl, cond = {}, {}
        for w, p in law.items():
            gv = tuple(ev(g, w) for g in gstar)
            kv = tuple(ev(k, w) for k in kappa)
            gl[gv] = gl.get(gv, Fraction(0)) + p
            cond.setdefault(gv, {})
            cond[gv][kv] = cond[gv].get(kv, Fraction(0)) + p
        new = {}
        for w, p in law.items():
            gv = tuple(ev(g, w) for g in gstar)
            for kv, q in cond[gv].items():
                nw = tuple(w) + kv
                new[nw] = new.get(nw, Fraction(0)) + p * q / gl[gv]
        law = new
    return law


def entropy_of_key(law, key, unit=math.log2(3)):
    """Entropy (in units of log2 3 = log|F_3|) of the forms in `key` under `law`."""
    agg = {}
    for w, p in law.items():
        val = tuple(sum(c * x for c, x in zip(f, w)) % 3 for f in key)
        agg[val] = agg.get(val, 0.0) + float(p)
    return -sum(p * math.log2(p) for p in agg.values() if p > 0) / unit


